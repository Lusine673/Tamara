import streamlit as st

st.set_page_config(
    page_title="Риск дисфункции ВНЧС при ортогнатической хирургии",
    layout="centered"
)

st.title("Дифференцированный алгоритм профилактики дисфункции ВНЧС\nпри ортогнатической хирургии")

st.markdown("### 1. Выберите тип скелетной аномалии челюстей")

anomalia = st.selectbox(
    "Скелетная аномалия",
    [
        "II скелетный класс",
        "III скелетный класс",
        "Асимметричная деформация челюстей",
        "Вертикальная резцовая дизокклюзия"
    ]
)

st.markdown("### 2. Клинические признаки дисфункции ВНЧС")

pain = st.checkbox("Боль в области ВНЧС")
noises = st.checkbox("Суставные шумы (щелчки, хруст, крепитация)")
lim_open = st.checkbox("Ограничение открывания рта")
deviation = st.checkbox("Девиация/дефлексия нижней челюсти")

st.markdown("### 3. Данные КЛКТ ВНЧС")

cbct_changes = st.checkbox("Выраженные изменения суставных щелей (верхний/задний/мезиальный отделы)")
cbct_asym = st.checkbox("Асимметрия положения мыщелков по КЛКТ")

st.markdown("### 4. Данные МРТ ВНЧС (если выполнена)")

mri_done = st.checkbox("МРТ ВНЧС выполнена")
disc_deform = st.checkbox("Деформация суставного диска")
disc_disp = st.checkbox("Дислокация диска (вентральная/медиальная/латеральная/задняя)")
fluid_inc = st.checkbox("Увеличение объёма внутрисуставной жидкости")
cond_lim = st.checkbox("Ограниченная смещаемость головки мыщелка")

st.markdown("---")

if st.button("Рассчитать риск дисфункции ВНЧС"):
    score = 0

    # Базовый риск по типу аномалии
    if anomalia == "II скелетный класс":
        score += 1
    elif anomalia == "III скелетный класс":
        score += 2
    elif anomalia == "Асимметричная деформация челюстей":
        score += 3
    elif anomalia == "Вертикальная резцовая дизокклюзия":
        score += 3

    # Клиника
    if pain: score += 2
    if noises: score += 1
    if lim_open: score += 2
    if deviation: score += 2

    # КЛКТ
    if cbct_changes: score += 2
    if cbct_asym: score += 2

    # МРТ (учитываем только если выполнена)
    if mri_done:
        if disc_deform: score += 2
        if disc_disp: score += 3
        if fluid_inc: score += 1
        if cond_lim: score += 2

    # Категории риска
    if score <= 4:
        risk_level = "Низкий риск"
        tactic = (
            "Рекомендуется стандартное ортогнатическое планирование с контролем положения мыщелков. "
            "Послеоперационный клинический контроль ВНЧС (1–3 и 6 месяцев); повторная визуализация "
            "(КЛКТ/МРТ) выполняется при появлении или усилении симптомов."
        )
    elif 5 <= score <= 8:
        risk_level = "Умеренный риск"
        tactic = (
            "Требуется тщательное планирование операции с учётом исходного состояния ВНЧС. "
            "Желательна МРТ (если ещё не выполнена), возможна корректировка объёма и/или вектора перемещений "
            "при выраженных суставных изменениях. Послеоперационный контроль ВНЧС (клиника + при необходимости "
            "КЛКТ/МРТ через 6 месяцев); рекомендуется щадящий режим жевательной нагрузки."
        )
    else:
        risk_level = "Высокий риск"
        tactic = (
            "Показано углублённое предоперационное обследование ВНЧС (обязательно МРТ), детальное ортогнатическое "
            "планирование с приоритетом сохранения/стабилизации положения мыщелков. Следует рассмотреть возможность "
            "комбинированного вмешательства при выраженной суставной патологии. Необходим жёсткий послеоперационный "
            "мониторинг (клиника + КЛКТ/МРТ), индивидуализация режима жевательной нагрузки и возможное привлечение "
            "гнатолога/ортопеда для коррекции остаточных внутрисуставных нарушений."
        )

    st.success(f"Итоговый балл риска: {score}")
    st.info(f"Категория риска: **{risk_level}**")
    st.markdown(f"**Рекомендуемая тактика:** {tactic}")
